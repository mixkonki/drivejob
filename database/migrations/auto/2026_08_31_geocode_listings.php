 * ΔΕΝ καλεί κανένα API. Ο πίνακας GreekPlaces καλύπτει κάθε πρωτεύουσα
 * νομού· ό,τι δεν βρεθεί μένει NULL και το αναφέρει, ώστε να ξέρουμε
 * πόσο μεγάλο είναι το υπόλοιπο.
 *
 * Idempotent: η δεύτερη εκτέλεση δεν βρίσκει τίποτα να κάνει.
