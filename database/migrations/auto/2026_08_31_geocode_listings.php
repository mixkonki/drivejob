require_once __DIR__ . '/../../../src/bootstrap.php';

use Drivejob\Helpers\GreekPlaces;

$pdo = require ROOT_DIR . '/config/database.php';
$pdo->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);

restore_exception_handler();
restore_error_handler();

/**
 * Γεμίζει lat/lng από στήλη κειμένου.
 *
 * @return array{0:int,1:int} [πόσα γέμισαν, πόσα έμειναν]
 */
$fill = static function (PDO $pdo, string $table, array $textColumns): array {
    $cols = implode(', ', $textColumns);
    $rows = $pdo->query(
        "SELECT id, {$cols} FROM {$table}
         WHERE (latitude IS NULL OR latitude = 0 OR longitude IS NULL OR longitude = 0)"
    )->fetchAll(PDO::FETCH_ASSOC);

    if (!$rows) {
        return [0, 0];
    }

    $update = $pdo->prepare("UPDATE {$table} SET latitude = ?, longitude = ? WHERE id = ?");
    $done = 0;
    $left = 0;

    foreach ($rows as $row) {
        // Οι στήλες δοκιμάζονται με σειρά προτεραιότητας: η πιο ειδική
        // πρώτη. «Θεσσαλονίκη» στο city είναι ασφαλέστερο από ένα
        // «Ελλάδα» που μπορεί να κρύβεται σε ελεύθερο κείμενο.
        $found = null;
        foreach ($textColumns as $col) {
            $found = GreekPlaces::locate($row[$col] ?? null);
            if ($found) {
                break;
            }
        }

        if ($found) {
            $update->execute([$found[0], $found[1], $row['id']]);
            $done++;
        } else {
            $left++;
        }
    }

    return [$done, $left];
};

// ── Αγγελίες ────────────────────────────────────────────────────────────
[$done, $left] = $fill($pdo, 'job_listings', ['location']);
echo "OK: αγγελίες — {$done} με συντεταγμένες, {$left} χωρίς αναγνωρίσιμη πόλη.\n";

// ── Οδηγοί ──────────────────────────────────────────────────────────────
// Η φόρμα τις γεμίζει από 30/08 (work-radius.js), αλλά όσοι δεν άνοιξαν
// έκτοτε το προφίλ τους έμειναν χωρίς — και είναι αόρατοι στο ταίριασμα
// απόστασης εξίσου με τις αγγελίες.
[$done, $left] = $fill($pdo, 'drivers', ['city', 'address']);
echo "OK: οδηγοί — {$done} με συντεταγμένες, {$left} χωρίς αναγνωρίσιμη πόλη.\n";
