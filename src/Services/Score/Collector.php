<?php

namespace Drivejob\Services\Score;

use PDO;

/**
 * Μία πηγή βαθμολογίας ξέρει ΜΟΝΟ να διαβάζει τον εαυτό της. (01/09/2026)
 *
 * Ο συνθέτης (DriverScoreService) δεν ξέρει τίποτα για άδειες, ADR ή
 * ταχογράφους — ρωτά κάθε collector «τι έχεις;» και παίρνει
 * Contribution[]. Έτσι η προσθήκη του ταχογράφου αύριο είναι μία κλάση
 * και μία γραμμή στο μητρώο, χωρίς να ακουμπήσει τίποτε άλλο.
 *
 * ΤΟ $profile ΕΙΝΑΙ ΤΟ ΙΔΙΟ ΠΟΥ ΤΡΩΕΙ Ο DriverCvService. Σκόπιμα: αν η
 * βαθμολογία διάβαζε τη βάση μόνη της, θα μπορούσε να διαφωνήσει με το
 * βιογραφικό — «η επισκόπηση λέει ότι το ADR έληξε, η βαθμολογία το
 * μετράει». Μία είσοδος, καμία απόκλιση.
 *
 * Ο PDO δίνεται για τις πηγές που ΔΕΝ είναι στο προφίλ (αξιολογήσεις
 * εργοδοτών, συμβάντα, τηλεματική).
 */
interface Collector
{
    /** Το κλειδί της πηγής στο ScoreSource::ALL */
    public function source(): string;

    /**
     * @param array $profile το πλήρες προφίλ (ίδιο με DriverCvService::build)
     * @return Contribution[] άδειο αν δεν υπάρχει τίποτα να μετρηθεί
     */
    public function collect(array $profile, PDO $pdo): array;
}
