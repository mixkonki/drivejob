 * **συμμόρφωση** — υπερβάσεις συνεχούς οδήγησης, ελλιπείς αναπαύσεις,
 * οδήγηση χωρίς κάρτα. Πρόστιμα και ευθύνη, όχι «σκορ οικολογικής
