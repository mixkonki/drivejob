 *  ΤΙ ΘΑ ΧΡΕΙΑΣΤΕΙ ΟΤΑΝ ΕΡΘΕΙ Η ΣΕΙΡΑ ΤΟΥ (βήμα 7)
 * ══════════════════════════════════════════════════════════════════════
 *
 *   1. Ανέβασμα .DDD από τον οδηγό (δικό του δικαίωμα στα δεδομένα του).
 *   2. Parser των μπλοκ δραστηριότητας + **έλεγχος ψηφιακής υπογραφής**.
 *      Χωρίς τον έλεγχο, το «αδύνατη η πλαστογραφία» παύει να ισχύει.
 *   3. Πίνακας `driver_tachograph_periods` (περίοδος, ώρες οδήγησης,
 *      αναπαύσεις, παραβάσεις) + άθροισμα εδώ.
 *   4. Διαγραφή του ωμού αρχείου μετά την επεξεργασία — κρατάμε
 *      συγκεντρωτικά, όχι ίχνη.
 *
 * Μέχρι τότε επιστρέφει κενό και το μητρώο το δηλώνει `active => false`,
 * ώστε η οθόνη να λέει «δεν έχει ενεργοποιηθεί» αντί να το κρύβει.
