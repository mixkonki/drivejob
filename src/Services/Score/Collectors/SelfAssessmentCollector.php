<?php

namespace Drivejob\Services\Score\Collectors;

use PDO;
use Drivejob\Services\Score\Collector;

/**
 * Αυτοαξιολόγηση — ΠΟΤΕ ΣΤΗ ΒΑΘΜΟΛΟΓΙΑ. (01/09/2026)
 *
 * ══════════════════════════════════════════════════════════════════════
 *  ΤΟ ΣΦΑΛΜΑ ΠΟΥ ΑΝΤΙΚΑΘΙΣΤΑ
 * ══════════════════════════════════════════════════════════════════════
 *
 * Ο πίνακας `driver_assessment` έχει 18 πεδία αυτοβαθμολόγησης
 * (punctuality, appearance, documentation, navigation_skills…). Ο παλιός
 * υπολογισμός έβγαζε από αυτά το 45% της συνολικής βαθμολογίας:
 *
 *     Επαγγελματισμός 25% + Τεχνικές δεξιότητες 20%
 *
 * Δύο προβλήματα, το ένα χειρότερο από το άλλο:
 *
 * 1. **Δεν υπάρχει φόρμα.** Κανένα view του project δεν περιέχει αυτά τα
 *    πεδία. Ο κώδικας έκανε `if (!$assessment) return 50;` — άρα κάθε
 *    οδηγός έπαιρνε 22,5 ίδιες μονάδες, χωρίς να αγγίξει τίποτα.
 *
 * 2. **Ακόμη κι αν υπήρχε φόρμα, δεν θα έπρεπε να μετράει.** Αριθμός που
 *    ο αξιολογούμενος ανεβάζει μόνος του δεν είναι αξιολόγηση, είναι
 *    δήλωση. Ο πρώτος εργοδότης που το καταλαβαίνει σταματά να κοιτάζει
 *    τον αριθμό — και μαζί του σταματά να κοιτάζει και ό,τι ήταν αληθινό.
 *
 * ══════════════════════════════════════════════════════════════════════
 *  Η ΠΡΑΓΜΑΤΙΚΗ ΤΗΣ ΧΡΗΣΗ
 * ══════════════════════════════════════════════════════════════════════
 *
 * Η αυτοαξιολόγηση ΕΧΕΙ αξία — απλώς όχι ως βαθμός. Είναι εργαλείο
 * **αυτογνωσίας και πλοήγησης**: «δήλωσες ότι είσαι δυνατός στη νυχτερινή
 * οδήγηση αλλά δεν έχεις κανένα σχετικό σεμινάριο — δες αυτό».
 *
 * Εκεί ζει και το εμπορικό ενδιαφέρον του ομίλου: η απόσταση ανάμεσα σε
 * «τι νομίζω ότι ξέρω» και «τι μπορώ να αποδείξω» είναι ακριβώς ο
 * κατάλογος εκπαίδευσης.
 *
 * Παραμένει `active => false` μέχρι να γραφτεί η φόρμα. Όταν γραφτεί,
 * θα τροφοδοτεί τις προτάσεις — ΟΧΙ τον αριθμό.
 */
final class SelfAssessmentCollector implements Collector
{
    public function source(): string
    {
        return 'self_assessment';
    }

    public function collect(array $profile, PDO $pdo): array
    {
        return [];
    }
}
