<?php

namespace Drivejob\Services\Score\Collectors;

use PDO;
use Drivejob\Services\Score\Collector;

/**
 * Ασφαλιστικό ιστορικό (ένσημα) — ΘΕΣΗ ΚΡΑΤΗΜΕΝΗ. (01/09/2026)
 *
 * ══════════════════════════════════════════════════════════════════════
 *  Η ΙΔΕΑ (του Κώστα, 01/09): «η προϋπηρεσία μπορεί να αποδειχθεί
 *  και από τα ένσημα»
 * ══════════════════════════════════════════════════════════════════════
 *
 * Σωστή, και ισχυρότερη απ' όσο ακούγεται. Ο e-ΕΦΚΑ δίνει σε κάθε
 * ασφαλισμένο, μέσω gov.gr, δύο σχετικά έγγραφα:
 *
 *   1. «Βεβαίωση Προϋπηρεσίας» — ΚΑΤΑ ΕΡΓΟΔΟΤΗ: επωνυμία, περίοδοι,
 *      ημέρες ασφάλισης, ΚΑΙ ΚΩΔΙΚΟ ΕΙΔΙΚΟΤΗΤΑΣ. Για οδηγό, η
 *      ειδικότητα γράφει «ΟΔΗΓΟΣ» — δηλαδή αποδεικνύει όχι μόνο ΟΤΙ
 *      δούλεψε αλλά ΟΤΙ ΔΟΥΛΕΨΕ ΩΣ ΟΔΗΓΟΣ.
 *   2. «Λογαριασμός Ασφάλισης» — αναλυτικά ένσημα ανά μήνα.
 *
 * Και τα δύο εκδίδονται ΑΠΟ ΤΟΝ ΙΔΙΟ τον οδηγό (δικά του δεδομένα,
 * κανένα ζήτημα συγκατάθεσης τρίτου) και φέρουν ΨΗΦΙΑΚΗ ΣΦΡΑΓΙΔΑ του
 * gov.gr με ΚΩΔΙΚΟ ΕΠΑΛΗΘΕΥΣΗΣ: οποιοσδήποτε — και το DriveJob — μπορεί
 * να ελέγξει τη γνησιότητα στο docs.gov.gr με τον κωδικό του εγγράφου.
 *
 * Δηλαδή: τεκμήριο επιπέδου VERIFIED (κρατικό έγγραφο, επαληθεύσιμο),
 * για το πράγμα που σήμερα είναι το πιο αδύναμο σημείο του προφίλ —
 * την προϋπηρεσία, που είναι δηλωμένη και δεν μετράει.
 *
 * ══════════════════════════════════════════════════════════════════════
 *  ΠΩΣ ΘΑ ΥΛΟΠΟΙΗΘΕΙ (όταν έρθει η σειρά του)
 * ══════════════════════════════════════════════════════════════════════
 *
 *   1. Ο οδηγός κατεβάζει τη Βεβαίωση Προϋπηρεσίας από το gov.gr
 *      (Ασφάλιση → e-ΕΦΚΑ) και την ανεβάζει ως PDF.
 *   2. Parser εξάγει: εργοδότες, περιόδους, ημέρες ασφάλισης, κωδικό
 *      ειδικότητας. ΚΡΑΤΑΜΕ ΣΥΓΚΕΝΤΡΩΤΙΚΑ (σύνολο μηνών ως οδηγός ανά
 *      έτος) — ΟΧΙ το ίδιο το PDF μετά την επεξεργασία, γιατί περιέχει
 *      ΑΜΚΑ και πλήρες εργασιακό ιστορικό. Ελαχιστοποίηση δεδομένων.
 *   3. Ο κωδικός επαλήθευσης του εγγράφου ελέγχεται στο docs.gov.gr
 *      (χειροκίνητα από admin στην αρχή, αυτόματα αργότερα).
 *   4. Διασταύρωση με τη δηλωμένη προϋπηρεσία: όπου συμφωνούν, η
 *      εγγραφή στο vehicle_experience σημαίνεται «επαληθευμένη» και ο
 *      ExperienceCollector αρχίζει να δίνει μονάδες γι' αυτήν.
 *
 * ΤΙ ΔΕΝ ΑΠΟΔΕΙΚΝΥΕΙ: το ΤΙ οδηγούσε (νταλίκα ή βανάκι) και ΠΟΣΟ ΚΑΛΑ.
 * Γι' αυτά μένουν η σύσταση εργοδότη και ο ταχογράφος. Τα τρία μαζί
 * (ένσημα = πόσο καιρό, σύσταση = πόσο καλά, ταχογράφος = πόσο νόμιμα)
 * είναι πλήρης εικόνα που κανείς δεν μπορεί να φτιάξει στο χέρι.
 *
 * Μέχρι τότε: κενό, και το μητρώο το δηλώνει `active => false` ώστε ο
 * οδηγός να βλέπει ότι έρχεται.
 */
final class InsuranceRecordCollector implements Collector
{
    public function source(): string
    {
        return 'insurance_record';
    }

    public function collect(array $profile, PDO $pdo): array
    {
        return [];
    }
}
