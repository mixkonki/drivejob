<?php

namespace Drivejob\Core;

/**
 * Προστασία φορμών από αυτόματες υποβολές.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  ΤΙ ΑΝΤΙΚΑΘΙΣΤΑ
 * ══════════════════════════════════════════════════════════════════════════
 *
 * Οι φόρμες εγγραφής είχαν ένα checkbox «Δεν είμαι ρομπότ» με `required`.
 * Δεν ελεγχόταν ΠΟΥΘΕΝΑ στον server — αναζήτηση για `human_check` σε όλο
 * το `src/` εκτός των views δεν επέστρεφε ούτε ένα αποτέλεσμα.
 *
 * Αυτό σημαίνει ότι η προστασία υπήρχε μόνο για όποιον άνοιγε τη σελίδα
 * σε browser. Ένα script που στέλνει POST απευθείας δεν βλέπει ποτέ το
 * HTML: το `required` είναι οδηγία προς τον browser, όχι προς τον server.
 * Το πεδίο κόστιζε μια γραμμή στη φόρμα και δεν σταματούσε τίποτα.
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  ΤΙ ΚΑΝΕΙ ΑΝΤ' ΑΥΤΟΥ
 * ══════════════════════════════════════════════════════════════════════════
 *
 * Δύο έλεγχοι που δεν ζητούν τίποτα από τον άνθρωπο:
 *
 *   1) ΔΟΛΩΜΑ — ένα πεδίο `website_url` κρυμμένο με CSS. Ο χρήστης δεν το
 *      βλέπει ποτέ και δεν το φτάνει με Tab. Τα αυτόματα scripts διαβάζουν
 *      το HTML και γεμίζουν ό,τι μοιάζει με πεδίο. Συμπληρωμένο = bot.
 *
 *      Δεν κρύβεται με `type="hidden"`: τα καλογραμμένα bots παρακάμπτουν
 *      τα hidden. Κρύβεται οπτικά, ώστε να μοιάζει κανονικό στον κώδικα.
 *
 *   2) ΧΡΟΝΟΣ — πόσο πέρασε από τη φόρτωση της φόρμας. Επτά πεδία, ένα
 *      συνθηματικό δύο φορές και μια ματιά στους όρους δεν γίνονται σε δύο
 *      δευτερόλεπτα. Ένα script τα στέλνει σε μηδέν.
 *
 * ΓΙΑΤΙ ΕΙΝΑΙ ΑΝΕΚΤΙΚΟ: ένας πραγματικός χρήστης δεν πρέπει ΠΟΤΕ να
 * μπλοκαριστεί. Το χρονικό κατώφλι είναι σκόπιμα χαμηλό (2 δευτ.) και η
 * απουσία της χρονοσήμανσης δεν θεωρείται ύποπτη — μπορεί να λείπει από
 * παλιά cached σελίδα. Προτιμάμε να περάσει ένα bot παρά να διωχθεί ένας
 * οδηγός που θέλει δουλειά.
 */
final class BotGuard
{
    /** Όνομα του πεδίου-δολώματος. Μοιάζει με κανονικό πεδίο φόρμας. */
    private const TRAP_FIELD = 'website_url';

    /** Το πεδίο με τη χρονοσήμανση φόρτωσης. */
    private const TIME_FIELD = 'form_started';

    /** Ελάχιστα δευτερόλεπτα για ανθρώπινη συμπλήρωση. */
    private const MIN_SECONDS = 2;

    /**
     * Μοιάζει αυτή η υποβολή με αυτόματη;
     *
     * @param array $post τα δεδομένα της φόρμας
     * @return string|null ο λόγος απόρριψης, ή null αν όλα καλά
     */
    public static function suspicion(array $post): ?string
    {
        if (!empty($post[self::TRAP_FIELD])) {
            return 'trap';
        }

        $started = isset($post[self::TIME_FIELD]) ? (int) $post[self::TIME_FIELD] : 0;

        // Χρονοσήμανση στο μέλλον σημαίνει πειραγμένη φόρμα.
        if ($started > time() + 60) {
            return 'future';
        }

        if ($started > 0 && (time() - $started) < self::MIN_SECONDS) {
            return 'too_fast';
        }

        return null;
    }

    /**
     * Ελέγχει και σταματά την υποβολή αν είναι ύποπτη.
     *
     * Το μήνυμα προς τον χρήστη είναι σκόπιμα ουδέτερο: δεν εξηγούμε ποιος
     * έλεγχος χτύπησε, γιατί αυτό θα ήταν οδηγίες παράκαμψης.
     *
     * @return bool true αν η υποβολή είναι καθαρή
     */
    public static function passes(array $post, string $redirectTo): bool
    {
        $reason = self::suspicion($post);

        if ($reason === null) {
            return true;
        }

        Logger::warning('BotGuard: ύποπτη υποβολή φόρμας', [
            'reason' => $reason,
            'uri' => $_SERVER['REQUEST_URI'] ?? '',
            'ip' => $_SERVER['REMOTE_ADDR'] ?? '',
        ]);

        Session::set('error_message', 'Η υποβολή δεν ολοκληρώθηκε. Δοκίμασε ξανά.');
        header('Location: ' . $redirectTo, true, 303);
        exit;
    }
}
