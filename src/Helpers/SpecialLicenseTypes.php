<?php

namespace Drivejob\Helpers;

/**
 * Ειδικές άδειες & πιστοποιητικά οδηγού — μία πηγή αλήθειας (30/08/2026).
 *
 * Πριν ήταν ελεύθερο κείμενο: ο ένας έγραφε «εδχ», ο άλλος «ΕΔΧ ταξί»,
 * ο τρίτος «ταξι» — τρεις διαφορετικές τιμές για το ίδιο πράγμα. Έτσι
 * καμία ειδική άδεια δεν μπορούσε να μπει σε φίλτρο αγγελίας, σε
 * ταίριασμα ή σε βαθμολογία. Με τυποποιημένους κωδικούς, η εταιρεία
 * που ζητά «οδηγό ΕΔΧ» βρίσκει ακριβώς τους κατόχους.
 *
 * Ο κατάλογος ορίστηκε από τον Κώστα (εκπαιδευτή του κλάδου) και
 * καλύπτει ό,τι ζητά σήμερα η αγορά. Το «other» είναι δίχτυ ασφαλείας:
 * κρατά τον ελεύθερο τίτλο στο πεδίο «Περιγραφή» χωρίς να λερώνει την
 * ταξινομία.
 *
 * ΔΕΝ μπαίνουν εδώ: ADR, ΠΕΙ, κάρτα ταχογράφου και άδεια χειριστή ΜΕ
 * (έχουν δικές τους καρτέλες), ούτε σεμινάρια (πάνε στις πιστοποιήσεις).
 */
final class SpecialLicenseTypes
{
    public const TYPES = [
        'edx_taxi'      => 'Ειδική άδεια ΕΔΧ (ΤΑΞΙ)',
        'live_animals'  => 'Πιστοποιητικό Επάρκειας Οδηγών και Συνοδών Μεταφορικών Μέσων Ζώντων Ζώων',
        'rental_driver' => 'Πιστοποιητικό οδηγού για ενοικίαση οχήματος με οδηγό',
        'other'         => 'Άλλο πιστοποιητικό οδηγού',
    ];

    /** Σύντομες ετικέτες για πίνακες/κάρτες όπου δεν χωρά ο πλήρης τίτλος. */
    public const SHORT_LABELS = [
        'edx_taxi'      => 'ΕΔΧ (ΤΑΞΙ)',
        'live_animals'  => 'Μεταφορά ζώντων ζώων',
        'rental_driver' => 'Ενοικίαση με οδηγό',
        'other'         => 'Άλλο πιστοποιητικό',
    ];

    public static function isValid(string $code): bool
    {
        return isset(self::TYPES[$code]);
    }

    /**
     * Ετικέτα για εμφάνιση. Δέχεται και παλιές ελεύθερες τιμές (π.χ. «εδχ»)
     * που υπάρχουν ήδη στη βάση — τις επιστρέφει ως έχουν αντί για κενό.
     */
    public static function label(string $code): string
    {
        return self::TYPES[$code] ?? $code;
    }

    public static function shortLabel(string $code): string
    {
        return self::SHORT_LABELS[$code] ?? self::TYPES[$code] ?? $code;
    }
}
