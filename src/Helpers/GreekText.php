<?php

namespace Drivejob\Helpers;

/**
 * Ελληνικό κείμενο — κεφαλαία ΧΩΡΙΣ τόνους. (30/08/2026)
 *
 * ΓΙΑΤΙ: το `mb_strtoupper('Τυπικά προσόντα')` δίνει «ΤΥΠΙΚΆ ΠΡΟΣΌΝΤΑ» —
 * κρατά την οξεία, που στα ελληνικά κεφαλαία ΔΕΝ μπαίνει. Το ίδιο έκανε
 * και το CSS `text-transform: uppercase`. Το βιογραφικό έβγαινε με
 * «ΤΥΠΙΚΆ ΠΡΟΣΌΝΤΑ», «ΠΡΟΫΠΗΡΕΣΊΑ», «ΣΕΜΙΝΆΡΙΑ».
 *
 * Ο κανόνας: μονοτονικά κεφαλαία δεν παίρνουν τόνο. Εξαίρεση το
 * διαλυτικό, που ΔΙΑΤΗΡΕΙΤΑΙ (ΠΡΟΫΠΗΡΕΣΙΑ, ΑΫΠΝΙΑ) γιατί δηλώνει
 * προφορά, όχι τονισμό.
 *
 * ΣΗΜΕΙΩΣΗ ΓΙΑ ΤΟ CSS: το `text-transform: uppercase` του browser έχει
 * το ίδιο πρόβλημα. Όπου εμφανίζονται κεφαλαία σε τίτλους, το κείμενο
 * γράφεται ήδη κεφαλαίο από εδώ ή αποφεύγεται το uppercase.
 */
class GreekText
{
    /** Τονισμένο → άτονο, με το διαλυτικό να επιβιώνει. */
    private const DETONE = [
        'Ά' => 'Α', 'Έ' => 'Ε', 'Ή' => 'Η', 'Ί' => 'Ι', 'Ό' => 'Ο', 'Ύ' => 'Υ', 'Ώ' => 'Ω',
        'Ϊ' => 'Ϊ', 'Ϋ' => 'Ϋ',            // διαλυτικά: μένουν
        'ΐ' => 'Ϊ', 'ΰ' => 'Ϋ',            // τόνος + διαλυτικό → μόνο διαλυτικό
        'Α΄' => 'Α',
    ];

    public static function upper(string $text): string
    {
        return strtr(mb_strtoupper($text, 'UTF-8'), self::DETONE);
    }
}
