<?php

namespace Drivejob\Helpers;

/**
 * «Πίσω εκεί απ' όπου ήρθα». (31/08/2026)
 *
 * ══════════════════════════════════════════════════════════════════════
 *  ΤΟ ΠΡΟΒΛΗΜΑ
 * ══════════════════════════════════════════════════════════════════════
 *
 * Οι σελίδες /drivers/vehicle-experience και /drivers/certifications
 * είναι αυτόνομες: τις ανοίγεις από το προφίλ, από τη φόρμα επεξεργασίας
 * ή από το βιογραφικό. Το κουμπί επιστροφής τους όμως ήταν καρφωτό:
 *
 *     <a href="<?= BASE_URL ?>drivers/edit-profile">← Επιστροφή στο προφίλ</a>
 *
 * Ό,τι κι αν πατούσες, σε πήγαινε στην ΕΠΕΞΕΡΓΑΣΙΑ — και μάλιστα στην
 * πρώτη της καρτέλα. Ο οδηγός που ήρθε από το προφίλ έχανε και τη σελίδα
 * και την καρτέλα του, και η ετικέτα έλεγε ψέματα («στο προφίλ», ενώ
 * πήγαινε στην επεξεργασία).
 *
 * ══════════════════════════════════════════════════════════════════════
 *  Η ΛΥΣΗ
 * ══════════════════════════════════════════════════════════════════════
 *
 * Ο σύνδεσμος που σε φέρνει λέει από πού ήρθες:
 *
 *     drivers/vehicle-experience?from=profile
 *     drivers/certifications?from=cv
 *
 * και το κουμπί επιστροφής διαβάζει το `from`.
 *
 * ΓΙΑΤΙ ΟΧΙ HTTP_REFERER: δεν στέλνεται πάντα (πολιτικές referrer,
 * bookmark, νέα καρτέλα) και δεν είναι δικός μας έλεγχος — ένα κουμπί
 * «πίσω» που άλλοτε δουλεύει κι άλλοτε όχι είναι χειρότερο από ένα
 * σταθερό.
 *
 * ΓΙΑΤΙ ΛΕΥΚΗ ΛΙΣΤΑ ΚΑΙ ΟΧΙ ΕΛΕΥΘΕΡΟ URL: το `?from=` έρχεται από τη
 * γραμμή διευθύνσεων, δηλαδή από τον καθένα. Αν το τυπώναμε ως href θα
 * ήταν open redirect — σελίδα του drivejob.gr που στέλνει όπου θέλει ο
 * επιτιθέμενος. Εδώ το `from` είναι ΚΛΕΙΔΙ σε πίνακα· ό,τι δεν
 * αναγνωρίζεται πέφτει στην προεπιλογή.
 */
class ReturnTo
{
    /**
     * κλειδί → [διαδρομή (με hash), ετικέτα κουμπιού]
     *
     * Το hash δουλεύει χάρη στο tab-deeplink.js: γυρνάς στην ΚΑΡΤΕΛΑ
     * που άφησες, όχι στην πρώτη της σελίδας.
     */
    private const TARGETS = [
        'profile' => ['drivers/profile#qualifications', 'Επιστροφή στο προφίλ'],
        'edit' => ['drivers/edit-profile#skills-tab', 'Επιστροφή στην επεξεργασία'],
        'cv' => ['drivers/cv', 'Επιστροφή στο βιογραφικό'],
    ];

    private const DEFAULT_KEY = 'profile';

    /** Το κλειδί προέλευσης, πάντα από τη λευκή λίστα. */
    public static function key(): string
    {
        $from = (string) ($_GET['from'] ?? '');

        return isset(self::TARGETS[$from]) ? $from : self::DEFAULT_KEY;
    }

    /** Πλήρες URL επιστροφής. */
    public static function url(): string
    {
        return BASE_URL . self::TARGETS[self::key()][0];
    }

    /** Ετικέτα που λέει την αλήθεια για το πού πάει. */
    public static function label(): string
    {
        return self::TARGETS[self::key()][1];
    }

    /**
     * Το ερώτημα που μπαίνει στους συνδέσμους ΠΡΟΣ τις αυτόνομες σελίδες.
     *
     *     <a href="<?= BASE_URL ?>drivers/certifications<?= ReturnTo::mark('profile') ?>">
     */
    public static function mark(string $key): string
    {
        return isset(self::TARGETS[$key]) ? '?from=' . $key : '';
    }
}
