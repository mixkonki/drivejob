    private const EARTH_KM = 6371;

    /**
     * Βρίσκει συντεταγμένες μέσα σε ελεύθερο κείμενο τοποθεσίας.
     *
     * Δέχεται ό,τι γράφει το πεδίο `location`: «Θεσσαλονίκη, Ελλάδα»,
     * «Αθήνα - Πειραιάς», «ΘΕΣΣΑΛΟΝΙΚΗ», «Νομός Πιερίας, Κατερίνη».
     *
     * Ταιριάζει το ΜΑΚΡΥΤΕΡΟ όνομα που περιέχεται στο κείμενο: το
     * «Άγιος Νικόλαος» πρέπει να κερδίσει, όχι κάποιο τυχαίο μικρότερο
     * που τυχαίνει να είναι υποσύνολο.
     *
     * @return array{0:float,1:float,2:string}|null [lat, lng, όνομα]
     */
    public static function locate(?string $text): ?array
    {
        if ($text === null || trim($text) === '') {
            return null;
        }

        $needle = self::normalize($text);
        $best = null;
        $bestLen = 0;

        foreach (self::CITIES as [$name, $lat, $lng]) {
            $norm = self::normalize($name);
            if (mb_strlen($norm) > $bestLen && str_contains($needle, $norm)) {
                $best = [$lat, $lng, $name];
                $bestLen = mb_strlen($norm);
            }
        }

        return $best;
    }

    /**
     * Κανονικοποίηση για σύγκριση: πεζά, χωρίς τόνους, χωρίς τελικό
     * σίγμα ως ξεχωριστό γράμμα.
     *
     * ΓΙΑΤΙ: το ίδιο μέρος γράφεται «Θεσσαλονίκη», «ΘΕΣΣΑΛΟΝΙΚΗ»,
     * «Θεσσαλονικη» και «θεσσαλονίκης». Χωρίς κανονικοποίηση θα
     * ταίριαζε μόνο η μία γραφή και το ταίριασμα θα έμενε τυφλό για
     * τις υπόλοιπες — δηλαδή θα λύναμε το πρόβλημα κατά το ένα τέταρτο.
     */
    private static function normalize(string $text): string
    {
        $map = [
            'ά' => 'α', 'έ' => 'ε', 'ή' => 'η', 'ί' => 'ι', 'ό' => 'ο', 'ύ' => 'υ', 'ώ' => 'ω',
            'ϊ' => 'ι', 'ΐ' => 'ι', 'ϋ' => 'υ', 'ΰ' => 'υ', 'ς' => 'σ',
        ];

        return strtr(mb_strtolower(trim($text), 'UTF-8'), $map);
    }

    /** Απόσταση σε χιλιόμετρα (haversine). */
    public static function distance(float $lat1, float $lng1, float $lat2, float $lng2): float
    {
        $toRad = M_PI / 180;
        $dLat = ($lat2 - $lat1) * $toRad;
        $dLng = ($lng2 - $lng1) * $toRad;

        $a = sin($dLat / 2) ** 2
            + cos($lat1 * $toRad) * cos($lat2 * $toRad) * sin($dLng / 2) ** 2;

        return self::EARTH_KM * 2 * atan2(sqrt($a), sqrt(1 - $a));
    }
