    /** Θεώρηση: πρώτη στη δωδεκαετία (Ν.5203/2025), επόμενες ανά οκταετία. */
    public const FIRST_INSPECTION_YEARS = 12;
    public const NEXT_INSPECTION_YEARS = 8;

    public static function subName(string $code): string
    {
        $speciality = strstr($code, '.', true) ?: $code;
        return self::SUB_SPECIALITIES[$speciality][$code] ?? '';
    }

    public static function isValidSub(string $code): bool
    {
        $speciality = strstr($code, '.', true) ?: $code;
        return isset(self::SUB_SPECIALITIES[$speciality][$code]);
    }

    /**
     * Παράθυρο επόμενης θεώρησης για το βιβλιάριο.
     *
     * @param string|null $issueDate      Ημ. χορήγησης της ΠΑΛΑΙΟΤΕΡΗΣ άδειας ('Y-m-d')
     * @param string|null $lastInspection Ημ. τελευταίας θεώρησης, αν έχει γίνει
     * @return array{start:string,end:string}|null ['start'=>'Y-01-01','end'=>'Y-06-30']
     */
    public static function inspectionWindow(?string $issueDate, ?string $lastInspection = null): ?array
    {
        if ($lastInspection && ($ts = strtotime($lastInspection)) !== false) {
            // Επόμενη θεώρηση: 8ετία από το έτος της τελευταίας θεώρησης.
            $year = (int) date('Y', $ts) + self::NEXT_INSPECTION_YEARS;
        } elseif ($issueDate && ($ts = strtotime($issueDate)) !== false) {
            // Πρώτη θεώρηση: η μέτρηση αρχίζει την 1/1 του επόμενου έτους
            // από τη χορήγηση· δωδεκαετία → προθεσμία το επόμενο εξάμηνο.
            $year = (int) date('Y', $ts) + 1 + self::FIRST_INSPECTION_YEARS;
        } else {
            return null;
        }

        return ['start' => $year . '-01-01', 'end' => $year . '-06-30'];
    }
